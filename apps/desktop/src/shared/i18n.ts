/** 面板里的日期：英文用 en-GB 的 "Thursday 13 November"，中文用 "11月13日星期四" */
export function formatDate(date: Date, language: Language): string {
  return new Intl.DateTimeFormat(language === 'zh' ? 'zh-CN' : 'en-GB', {
    weekday: 'long',
    day: 'numeric',
    month: 'long'
  }).format(date)
}
